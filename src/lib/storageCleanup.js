import { supabase } from './supabase'

// Дочистка файлов в Storage после удаления задач/проектов.
//
// Строки attachments уходят каскадом, а файлы в бакете — нет: триггер в БД
// складывает их пути в очередь, эта функция просит сервер её разобрать.
// Вызывается «вдогонку» и намеренно не влияет на результат удаления:
// если сеть отвалилась, очередь разберётся при следующем удалении
// или по расписанию — файлы не теряются, просто убираются позже.
export function purgeStorageSoon() {
  supabase.functions.invoke('purge-storage', { body: {} }).catch(() => {
    /* фоновая операция: пользователю сообщать не о чем */
  })
}
